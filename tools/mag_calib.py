#!/usr/bin/env python3
"""Hard/soft-iron ellipsoid fit (MATH_SPEC.md section 3.4); writes mag_cal.h.

Input is a type S capture (sensor frame, uncalibrated) taken while the board
is turned slowly through all orientations, away from metal.
"""

import argparse
import sys

import numpy as np

from telemetry_records import load_csv

MIN_SAMPLES = 600
MIN_SAMPLES_PER_DIRECTION = 30
DIRECTION_DOMINANCE = 0.7
NORM_STD_MAX = 0.02
CONDITION_MAX = 1.5
UG_PER_GAUSS = 1.0e6

HEADER_TEMPLATE = """\
/*
 * Magnetometer hard/soft-iron calibration, sensor frame (MATH_SPEC.md section
 * 3.4): m_cal = W * (m - V). Generated by tools/mag_calib.py.
 *
 * Fit of {samples} samples from {source}:
 * std(|m_cal|) / B_ref = {norm_std:.4f}, cond(W) = {condition:.3f}.
 */
#ifndef MAG_CAL_H_
#define MAG_CAL_H_

#define MAG_CAL_VALID 1

/* Local total field B_ref in gauss. */
#define MAG_CAL_FIELD_NORM_G {field_norm:.5f}f

static const float MAG_CAL_V[3] = {{ {v[0]:.6f}f, {v[1]:.6f}f, {v[2]:.6f}f }}; /* gauss */

static const float MAG_CAL_W[3][3] = {{
	{{ {w[0][0]:.6f}f, {w[0][1]:.6f}f, {w[0][2]:.6f}f }},
	{{ {w[1][0]:.6f}f, {w[1][1]:.6f}f, {w[1][2]:.6f}f }},
	{{ {w[2][0]:.6f}f, {w[2][1]:.6f}f, {w[2][2]:.6f}f }},
}};

#endif /* MAG_CAL_H_ */
"""


def load_field_gauss(path):
    capture = load_csv(path, "S")
    valid = capture["mag_valid"] != 0
    field = np.column_stack([capture["mmx_ug"], capture["mmy_ug"], capture["mmz_ug"]])
    return field[valid] / UG_PER_GAUSS


def coverage_counts(field):
    """Samples pointing along +X, -X, +Y, -Y, +Z, -Z once the mean is removed."""
    centered = field - field.mean(axis=0)
    norms = np.linalg.norm(centered, axis=1)
    counts = []
    for axis in range(3):
        for sign in (1.0, -1.0):
            counts.append(int(np.sum(sign * centered[:, axis] > DIRECTION_DOMINANCE * norms)))
    return counts


def fit_ellipsoid(field, field_norm):
    """Return (V, W) such that |W (m - V)| = field_norm on the fitted ellipsoid."""
    x, y, z = field[:, 0], field[:, 1], field[:, 2]
    design = np.column_stack([x * x, y * y, z * z, 2 * y * z, 2 * x * z, 2 * x * y,
                              2 * x, 2 * y, 2 * z, np.ones_like(x)])
    # The surface m^T A m + 2 beta^T m + c = 0 is the null direction of the design matrix.
    u = np.linalg.svd(design, full_matrices=False)[2][-1]
    if u[0] + u[1] + u[2] < 0.0:
        u = -u

    shape = np.array([[u[0], u[5], u[4]],
                      [u[5], u[1], u[3]],
                      [u[4], u[3], u[2]]])
    beta, c = u[6:9], u[9]
    if np.any(np.linalg.eigvalsh(shape) <= 0.0):
        raise ValueError("the fitted surface is not an ellipsoid")

    hard_iron = -np.linalg.solve(shape, beta)
    k = hard_iron @ shape @ hard_iron - c
    eigenvalues, eigenvectors = np.linalg.eigh(shape / k)
    soft_iron = field_norm * eigenvectors @ np.diag(np.sqrt(eigenvalues)) @ eigenvectors.T
    return hard_iron, soft_iron


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("capture", help="type S CSV from tools/capture.py")
    parser.add_argument("--field-norm", type=float, required=True,
                        help="local total field B_ref in gauss (NOAA WMM)")
    parser.add_argument("--out", default="app/src/sensor_hub/mag_cal.h")
    return parser.parse_args()


def main():
    args = parse_args()
    field = load_field_gauss(args.capture)
    counts = coverage_counts(field)
    print(f"samples: {len(field)}, per direction (+X -X +Y -Y +Z -Z): {counts}")
    if len(field) < MIN_SAMPLES or min(counts) < MIN_SAMPLES_PER_DIRECTION:
        print("FAIL: coverage is insufficient; nothing written")
        return 1

    hard_iron, soft_iron = fit_ellipsoid(field, args.field_norm)
    calibrated_norm = np.linalg.norm((field - hard_iron) @ soft_iron.T, axis=1)
    norm_std = float(np.std(calibrated_norm) / args.field_norm)
    condition = float(np.linalg.cond(soft_iron))

    print(f"V [G] = {hard_iron}")
    print(f"W =\n{soft_iron}")
    print(f"std(|m_cal|)/B_ref = {norm_std:.4f} (limit {NORM_STD_MAX})")
    print(f"cond(W) = {condition:.3f} (limit {CONDITION_MAX})")
    if norm_std >= NORM_STD_MAX or condition >= CONDITION_MAX:
        print("FAIL: acceptance criteria not met; nothing written")
        return 1

    with open(args.out, "w") as header:
        header.write(HEADER_TEMPLATE.format(samples=len(field), source=args.capture,
                                            norm_std=norm_std, condition=condition,
                                            field_norm=args.field_norm, v=hard_iron,
                                            w=soft_iron))
    print(f"PASS: {args.out} written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
